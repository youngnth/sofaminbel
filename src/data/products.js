export const COLOR_HEX_MAP = {
  beige: '#E6DEC8',
  grey: '#9A9A96',
  gray: '#9A9A96',
  green: '#556B57',
  navy: '#2E4057',
  brown: '#8B5A3C'
};

export function getColorHex(colorName, fallbackHex = '#D8CFC2') {
  if (!colorName) return fallbackHex;
  const key = String(colorName).trim().toLowerCase();
  if (COLOR_HEX_MAP[key]) return COLOR_HEX_MAP[key];
  for (const [name, hex] of Object.entries(COLOR_HEX_MAP)) {
    if (key.includes(name)) return hex;
  }
  return fallbackHex;
}

export function formatVND(amount) {
  if (typeof amount !== 'number') return '';
  return `${amount.toLocaleString('en-US')}\u00A0₫`;
}

export function formatVNDWithCode(amount) {
  if (typeof amount !== 'number') return '';
  return `VND\u00A0${amount.toLocaleString('en-US')}`;
}
